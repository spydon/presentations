-- Questions asked by the audience during the Q&A.
create table public.questions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 40),
  content text not null check (char_length(content) between 1 and 280),
  created_at timestamptz not null default now()
);

alter table public.questions enable row level security;

-- The presentation itself runs without a session, so everyone can read.
create policy "Questions are public"
  on public.questions for select
  to anon, authenticated
  using (true);

-- Only signed in, non-anonymous users can ask, and only as themselves.
create policy "Signed in users ask as themselves"
  on public.questions for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and coalesce((select auth.jwt() ->> 'is_anonymous')::boolean, false) = false
  );

create policy "Users delete their own questions"
  on public.questions for delete
  to authenticated
  using (user_id = (select auth.uid()));

-- Deliver inserts and deletes to the live question wall.
alter publication supabase_realtime add table public.questions;
